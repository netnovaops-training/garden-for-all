// Updater.kt -- the in-app updater.
//
// Once per launch it reads <garden>/apps/version.json (the garden's CURRENT address,
// GardenAddress.kt, so the updater follows a move too). If that file names a higher
// versionCode than the app that is running, it offers the update, downloads the APK, checks
// the file arrived whole (sha256; md5 only for an older version.json without sha256),
// and hands it to Android's installer, which always asks the person first.

package org.jasonagibson.junsgarden.app

import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.jasonagibson.junsgarden.BuildConfig
import org.jasonagibson.junsgarden.garden.GardenAddress
import org.json.JSONObject
import java.io.File
import java.net.HttpURLConnection
import java.net.URL
import java.security.MessageDigest

/**
 * Updates the app from the garden website, without a trip to the browser.
 *
 * WHY A MANIFEST AND NOT JUST DOWNLOADING THE APK. The APK is 40MB. Checking
 * for an update by fetching it would cost 40MB every launch to answer a
 * question whose answer is almost always "no". version.json is a few hundred
 * bytes and carries the versionCode, so the download happens only when there
 * is genuinely something new -- which is the whole point of the request that
 * led to this.
 *
 * THE MANIFEST IS GENERATED BY THE RELEASE SCRIPT, from the same build that
 * produced the APK beside it. A hand-maintained one would eventually claim a
 * version that was never published, and the app would offer an update that
 * downloads the build it already has.
 *
 * WHAT THIS DOES NOT DO: install silently. Android shows its own confirmation
 * and requires "install unknown apps" to have been allowed for this app once.
 * That prompt is a feature -- an app that can replace itself without asking
 * is an app that can be replaced without asking.
 */
class Updater {

    data class Available(
        val versionCode: Int,
        val versionName: String,
        val url: String,
        val sha256: String,
        val md5: String,
        val notes: String,
    )

    /** Null when the site has nothing newer than what is running. */
    suspend fun check(): Available? = withContext(Dispatchers.IO) {
        val conn = (URL(MANIFEST).openConnection() as HttpURLConnection).apply {
            requestMethod = "GET"
            setRequestProperty("Accept", "application/json")
            // no-store, not no-cache: a stale manifest would hide a release,
            // and this is small enough that never caching it costs nothing.
            setRequestProperty("Cache-Control", "no-store")
            connectTimeout = 10_000
            readTimeout = 15_000
        }
        try {
            if (conn.responseCode !in 200..299) return@withContext null
            val json = JSONObject(conn.inputStream.bufferedReader().use { it.readText() })
            val code = json.optInt("versionCode", -1)
            if (code <= BuildConfig.VERSION_CODE) return@withContext null

            Available(
                versionCode = code,
                versionName = json.optString("versionName"),
                url = json.optString("url").ifBlank { DEFAULT_APK },
                sha256 = json.optString("sha256"),
                md5 = json.optString("md5"),
                notes = json.optString("notes"),
            )
        } catch (_: Exception) {
            // A failed check is not worth telling anybody about. The app works;
            // it simply does not know whether a newer one exists.
            null
        } finally {
            conn.disconnect()
        }
    }

    /**
     * Downloads the update and hands it to Android's installer.
     *
     * VERIFIES THE CHECKSUM BEFORE INSTALLING. A truncated download is a
     * corrupt APK, and Android's installer reports that as a generic parse
     * failure that looks like a bad build rather than a bad transfer. The
     * manifest carries the md5 of the exact file the release script published,
     * so a mismatch is caught here with a sentence that says what happened.
     */
    suspend fun downloadAndInstall(
        context: Context,
        update: Available,
        onProgress: (Int) -> Unit,
    ) = withContext(Dispatchers.IO) {
        val dir = File(context.cacheDir, "updates").apply { mkdirs() }
        // One file, replaced each time: keeping old APKs around would leave
        // 40MB per release sitting in the cache forever.
        val target = File(dir, "update.apk")
        target.delete()

        val conn = (URL(update.url).openConnection() as HttpURLConnection).apply {
            connectTimeout = 20_000
            readTimeout = 300_000
        }

        try {
            if (conn.responseCode !in 200..299) {
                throw IllegalStateException("The download failed (${conn.responseCode}).")
            }
            val total = conn.contentLengthLong
            // SHA-256 when the manifest has it; md5 only for a manifest from before it did.
            val useSha = update.sha256.length == 64
            val digest = MessageDigest.getInstance(if (useSha) "SHA-256" else "MD5")

            conn.inputStream.use { input ->
                target.outputStream().use { out ->
                    val buf = ByteArray(64 * 1024)
                    var read: Int
                    var done = 0L
                    while (input.read(buf).also { read = it } >= 0) {
                        out.write(buf, 0, read)
                        digest.update(buf, 0, read)
                        done += read
                        if (total > 0) onProgress(((done * 100) / total).toInt())
                    }
                }
            }

            val got = digest.digest().joinToString("") { "%02x".format(it) }
            val want = if (useSha) update.sha256 else update.md5
            if (want.isNotBlank() && !got.equals(want, ignoreCase = true)) {
                target.delete()
                throw IllegalStateException(
                    "The download did not arrive intact, so it was not installed. Try again."
                )
            }
        } finally {
            conn.disconnect()
        }

        val uri: Uri = FileProvider.getUriForFile(
            context, "${context.packageName}.fileprovider", target
        )

        val intent = Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(uri, "application/vnd.android.package-archive")
            // The installer runs as another app, so it needs read access to
            // this specific file, granted for this specific intent.
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(intent)
    }

    companion object {
        private val MANIFEST get() = GardenAddress.base + "/apps/version.json"
        private val DEFAULT_APK get() = GardenAddress.base + "/apps/junsgarden.apk"
    }
}
